"""Regenerate docs/TOOLS.md (English) and docs/TOOLS.es.md (Spanish) from the tool definitions.

    python scripts/gen_tools_doc.py
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from arr_doctor.config import Settings  # noqa: E402
from arr_doctor.server import build_server  # noqa: E402

GROUPS = [
    ({"en": "Status", "es": "Estado"}, ["get_system_status"]),
    ({"en": "Library (read-only)", "es": "Catálogo (solo lectura)"},
     ["search_library", "get_series", "get_episodes", "get_movie", "get_missing", "get_cutoff_unmet", "get_calendar"]),
    ({"en": "Diagnostics (read-only)", "es": "Diagnóstico (solo lectura)"},
     ["get_queue", "get_history", "get_blocklist", "get_health", "get_logs", "get_disk_space",
      "find_orphan_downloads", "find_suspicious_releases", "get_command_status"]),
    ({"en": "Troubleshooting", "es": "Resolución de problemas"},
     ["explain_search", "grab_release", "diagnose_import", "check_paths", "find_stalled_downloads", "parse_release"]),
    ({"en": "Maintenance", "es": "Mantenimiento"},
     ["library_report", "bulk_edit_preview", "bulk_edit_apply", "preview_rename", "rename_files", "test_download_clients"]),
    ({"en": "Actions (write)", "es": "Acciones (escritura)"},
     ["search_episodes", "search_season", "search_missing", "search_movie", "set_monitored", "remove_from_queue",
      "refresh_item", "add_series", "add_movie", "manual_import"]),
    ({"en": "Prowlarr", "es": "Prowlarr"}, ["list_indexers", "get_indexer_stats", "set_indexer_enabled", "test_indexers"]),
]

TEXT = {
    "en": {
        "title": "# Tool reference",
        "other": "Versión en español: [TOOLS.es.md](TOOLS.es.md).",
        "generated": "<!-- Generated by scripts/gen_tools_doc.py. Do not edit by hand. -->",
        "intro": "Write tools are not registered when `ARR_READONLY=true`, and the tools of a service that is not\n"
        "configured are not registered either.",
        "readonly": "read-only", "destructive": "**destructive**", "write": "write", "requires": "requires {svc}",
        "queries_indexers": "contacts external services",
        "header": "| Parameter | Type | Default | Description |", "required": "required",
    },
    "es": {
        "title": "# Referencia de tools",
        "other": "English version: [TOOLS.md](TOOLS.md).",
        "generated": "<!-- Generado por scripts/gen_tools_doc.py. No editar a mano. -->",
        "intro": "Las descripciones están en inglés porque son lo que lee el modelo para elegir la tool.\n"
        "Las tools de escritura no se registran con `ARR_READONLY=true`, y las de un servicio sin\n"
        "configurar tampoco.",
        "readonly": "solo lectura", "destructive": "**destructiva**", "write": "escritura", "requires": "requiere {svc}",
        "queries_indexers": "contacta con servicios externos",
        "header": "| Parámetro | Tipo | Por defecto | Descripción |", "required": "obligatorio",
    },
}

NEEDS = {
    "get_series": "Sonarr", "get_episodes": "Sonarr", "search_episodes": "Sonarr", "search_season": "Sonarr",
    "add_series": "Sonarr", "get_movie": "Radarr", "search_movie": "Radarr", "add_movie": "Radarr",
    "list_indexers": "Prowlarr", "get_indexer_stats": "Prowlarr", "set_indexer_enabled": "Prowlarr",
    "test_indexers": "Prowlarr",
}


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        return " \\| ".join(_type(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if schema.get("type") == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    return schema.get("type", "any")


async def build(lang: str = "en") -> str:
    tx = TEXT[lang]
    settings = Settings(
        _env_file=None, sonarr_url="http://s", sonarr_api_key="k", radarr_url="http://r", radarr_api_key="k",
        prowlarr_url="http://p", prowlarr_api_key="k",
    )
    tools = await build_server(settings).get_tools()
    lines = [tx["title"], "", tx["generated"], "", tx["other"], "", tx["intro"], ""]
    documented: set[str] = set()
    for titles, names in GROUPS:
        lines += [f"## {titles[lang]}", ""]
        for name in names:
            tool = tools[name]
            documented.add(name)
            ann = tool.annotations
            flags = []
            if ann and ann.readOnlyHint:
                flags.append(tx["readonly"])
                if ann.openWorldHint:
                    flags.append(tx["queries_indexers"])
            if ann and ann.destructiveHint:
                flags.append(tx["destructive"])
            elif ann and ann.readOnlyHint is False:
                flags.append(tx["write"])
            if name in NEEDS:
                flags.append(tx["requires"].format(svc=NEEDS[name]))
            lines += [f"### `{name}`", "", f"_{' · '.join(flags)}_", "", (tool.description or "").strip(), ""]
            props = tool.parameters.get("properties", {})
            required = set(tool.parameters.get("required", []))
            if props:
                lines += [tx["header"], "|---|---|---|---|"]
                for pname, schema in props.items():
                    default = tx["required"] if pname in required else f"`{schema.get('default')!r}`".replace("None", "null")
                    lines.append(f"| `{pname}` | {_type(schema)} | {default} | {schema.get('description', '')} |")
                lines.append("")
    missing = set(tools) - documented
    if missing:
        raise SystemExit(f"Tools without a group in gen_tools_doc.py: {sorted(missing)}")
    return "\n".join(lines).rstrip() + "\n"


OUTPUTS = {"en": "TOOLS.md", "es": "TOOLS.es.md"}


if __name__ == "__main__":
    for lang, filename in OUTPUTS.items():
        out = ROOT / "docs" / filename
        out.parent.mkdir(exist_ok=True)
        out.write_text(asyncio.run(build(lang)), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")
